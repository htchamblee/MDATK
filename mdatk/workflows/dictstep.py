# for both Phenix versions / current acedrg are used (see the notes of 0.0.3c for what is unverified).
PHENIX_VERSIONS: Dict[str, Dict[str, str]] = {
    "1.21": {"label": "Phenix 1.21", "env_script": "phenix_env.sh", "example": "/usr/local/phenix-1.21.2-5419",
             "elbow": "phenix.elbow"},
    "2.x": {"label": "Phenix 2.x", "env_script": "phenix_env.sh", "example": "/usr/local/phenix-2.0-5936",
            "elbow": "phenix.elbow"},
}
CCP4_SETUP_EXAMPLE = "/opt/xtal/ccp4-9/bin/ccp4.setup-sh"
# {exe} program, {smi} SMILES file, {code} residue code, {out} output root (the program adds .cif / .pdb)
PROGRAM_COMMANDS = {
    "acedrg": "{exe} -i {smi} -r {code} -o {out}",
    "phenix.elbow": "{exe} {smi} --id={code} --output={out}",
}
PROGRAM_LABELS = {"acedrg": "acedrg", "phenix.elbow": "phenix.elbow"}
RESOURCE_IDS = {"acedrg": "acedrg", "phenix.elbow": "phenix_elbow"}

_CODE_RE = re.compile(r"^[A-Za-z0-9]{1,5}$")
_PDB_CACHE: Dict[Tuple[str, float], Tuple[List[str], str]] = {}
_PUBCHEM: Dict[Tuple[str, float], str] = {}  # (CID or name, timeout) -> SMILES fetched this session


def parse_entries(text: str, what: str = "SMILES") -> Tuple[List[Tuple[str, str]], List[str]]:
    """'code = value' lines -> ([(CODE, value)], problems); blank lines and # comments are skipped."""
    out: List[Tuple[str, str]] = []
    problems: List[str] = []
    for k, line in enumerate((text or "").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            problems.append(f"line {k}: expected 'code = {what}'")
            continue
        code, value = (p.strip() for p in line.split("=", 1))
        if not _CODE_RE.match(code):
            problems.append(f"line {k}: {code!r} is not a residue code (1-5 letters / digits)")
            continue
        if not value:
            problems.append(f"line {k}: no {what} for {code}")
            continue
        out.append((code.upper(), value))
    return out, problems


def variant_codes_in_pdb(path: str) -> Tuple[List[str], str]:
    """L-RNA terminal variants (0A5 ...) the 'ccd' naming scheme gives the residues of a PDB file.

    Chirality comes from the sugar geometry, so Amber (LA5) or cpptraj (A) names work as well.  Returns
    (codes, problem); cached by path and modification time."""
    try:
        key = (path, os.path.getmtime(path))
    except OSError as exc:
        return [], str(exc)
    if key not in _PDB_CACHE:
        try:
            s = pdbtools.read_pdb(path)
            pdbtools.assign_chirality(s, detect=True)
            pdbtools.convert_names(s, "ccd")
            names = {r.name for r in s.residues()}
            codes = [c for c, comp in dictionaries.COMPONENTS.items() if comp.is_variant and c in names]
            _PDB_CACHE[key] = (codes, "")
        except (OSError, pdbtools.PDBError) as exc:
            _PDB_CACHE[key] = ([], f"could not read {os.path.basename(path)}: {exc}")
    return _PDB_CACHE[key]


