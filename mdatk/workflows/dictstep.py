"""Planner step writing acedrg / phenix.elbow restraint dictionaries (mdatk.dictionaries).

For every residue code the step writes a SMILES file, runs acedrg (CCP4) or phenix.elbow (Phenix) on it in
its own work folder and then a copy of :mod:`mdatk.dictionaries` ('finish') renames the program's atoms to
the model's CCD / PDB atom names and sets the component id and group.  The output port carries one
``<code>`` dictionary per residue for Coot / Phenix.

The SMILES come from MDATK's built-in table, from 'code = SMILES' lines typed by the user, or - only when
the PubChem option is switched on - from PubChem while the files are written (the single network access).
"""

