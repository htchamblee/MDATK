    # ------------------------------------------------------------- codes
    def _codes(self, s, ctx) -> Tuple[List[str], List[Issue]]:
        issues: List[Issue] = []
        mode = s["codes_mode"]
        custom = dict(parse_entries(s["custom"])[0])
        if mode == "list":
            codes = [c.upper() for c in re.split(r"[\s,;]+", s["codes"].strip()) if c]
        elif mode == "all":
            codes = list(dictionaries.COMPONENTS)
        else:
            codes = [c for c, comp in dictionaries.COMPONENTS.items() if comp.is_variant]
            if mode == "auto" and ctx.has("structure"):
                path = ctx.existing("structure")
                if not path:
                    issues.append(Issue("info", "the model does not exist yet; dictionaries for all eight variants "
                                                "are written", ("codes_mode",)))
                else:
                    found, problem = variant_codes_in_pdb(path)
                    if problem:
                        issues.append(Issue("warning", f"{problem}; writing all eight variants",
                                            ("input:structure",)))
                    else:
                        codes = found
                        if not found:
                            issues.append(Issue("error", "the model has no L-RNA chain ends (0A5/0A3 ... in CCD "
                                                         "naming); choose the residues by hand",
                                                ("codes_mode", "input:structure")))
            if mode == "auto":  # custom codes that are not in the table are wanted as well
                codes += [c for c in custom if c not in dictionaries.COMPONENTS and c not in codes]
        return list(dict.fromkeys(codes)), issues

    def resources(self, s):
        out = [RESOURCE_IDS[s["program"]], "ccd"]
        if s["pubchem_fetch"] and parse_entries(s["pubchem_ids"], "CID")[0]:
            out.append("pubchem")
        return out

    def describe(self, s):
        mode = {"auto": "variants in the model", "variants": "8 variants", "all": "12 codes"}.get(
            s["codes_mode"], s["codes"].strip() or "no codes")
        return f"{PROGRAM_LABELS[s['program']]}: {mode}"

    def output_values(self, s, ctx):
        codes, _ = self._codes(s, ctx)
        if not codes:
            return {}
        return {"dictionaries": PortValue([ctx.own(c, "cif") for c in codes], "cif",
                                          {"codes": codes, "group": s["group"]})}

    def check(self, s, ctx):
        out: List[Issue] = []
        codes, issues = self._codes(s, ctx)
        out += issues
        if s["codes_mode"] == "list" and not codes:
            out.append(Issue("error", "type the residue codes", ("codes",)))
        bad = [c for c in codes if not _CODE_RE.match(c)]
        if bad:
            out.append(Issue("error", f"not a residue code: {', '.join(bad)}", ("codes",)))
        long_codes = [c for c in codes if len(c) > 3 and c not in bad]
        if long_codes:
            out.append(Issue("warning", f"PDB residue names have at most 3 characters: {', '.join(long_codes)}",
                             ("codes", "custom")))
        entries, problems = parse_entries(s["custom"])
        out += [Issue("error", f"Custom SMILES {p}", ("custom",)) for p in problems]
        for code, smiles in entries:
            if code in dictionaries.COMPONENTS:
                try:
                    dictionaries.check_smiles(code, smiles)
                except dictionaries.DictionaryError as exc:
                    out.append(Issue("error", f"custom SMILES for {code}: {exc}", ("custom",)))
            else:
                try:
                    dictionaries.parse_smiles(smiles)
                except dictionaries.DictionaryError as exc:
                    out.append(Issue("error", f"custom SMILES for {code}: {exc}", ("custom",)))
                    continue
                out.append(Issue("warning", f"{code} is not in MDATK's table: its dictionary keeps the atom names "
                                            f"{PROGRAM_LABELS[s['program']]} invents, which the model must use",
                                 ("custom",)))
            if code not in codes:
                out.append(Issue("warning", f"custom SMILES for {code}, which is not generated", ("custom",)))
        missing = [c for c in codes if c not in dictionaries.COMPONENTS and c not in dict(entries)]
        if missing and not (s["pubchem_fetch"] and all(c in dict(parse_entries(s["pubchem_ids"], "CID")[0])
                                                        for c in missing)):
            out.append(Issue("error", f"no SMILES for {', '.join(missing)}: add 'code = SMILES' lines",
                             ("codes", "custom")))
        if s["pubchem_fetch"]:
            ids, problems = parse_entries(s["pubchem_ids"], "CID")
            out += [Issue("error", f"PubChem compounds {p}", ("pubchem_ids",)) for p in problems]
            if not ids and not problems:
                out.append(Issue("warning", "PubChem is switched on but no 'code = CID' line is given",
                                 ("pubchem_ids",)))
            elif ids:
                out.append(Issue("info", "the SMILES of " + ", ".join(c for c, _ in ids) + " are downloaded from "
                                         "PubChem when the files are written (network access)", ("pubchem_fetch",)))
            for code, _cid in ids:
                if code not in codes:
                    out.append(Issue("warning", f"PubChem entry for {code}, which is not generated",
                                     ("pubchem_ids",)))
                if code in dict(entries):
                    out.append(Issue("info", f"{code}: the PubChem SMILES replaces the custom one",
                                     ("pubchem_ids",)))
        if s["group"] != "RNA":
            out.append(Issue("info", "non-polymer: Coot / Phenix will not link these residues to their neighbours "
                                     "(no backbone restraints across the link)", ("group",)))
        parents = [c for c in codes if c in dictionaries.COMPONENTS and not dictionaries.COMPONENTS[c].is_variant]
        if parents:
            out.append(Issue("info", f"{', '.join(parents)} are CCD entries that Coot and Phenix already ship; "
                                     "the regenerated dictionaries replace theirs", ("codes_mode",)))
        if s["program"] == "phenix.elbow" and not s["phenix_dir"].strip() and not s["env_setup"].strip() \
                and not s["conda_env"].strip():
            out.append(Issue("info", "phenix.elbow must be on PATH (or set the Phenix installation)",
                             ("phenix_dir",)))
        if s["program"] == "acedrg" and not s["ccp4_setup"].strip() and not s["env_setup"].strip() \
                and not s["conda_env"].strip():
            out.append(Issue("info", "acedrg must be on PATH (or set the CCP4 setup script)", ("ccp4_setup",)))
        return out

    # ------------------------------------------------------------- files
    def _smiles(self, s, codes: List[str], preview: bool = False) -> Tuple[Dict[str, Tuple[str, str]], List[str]]:
        """code -> (SMILES, source description); notes on PubChem problems (fetching happens here)."""
        out: Dict[str, Tuple[str, str]] = {}
        notes: List[str] = []
        for c in codes:
            if c in dictionaries.COMPONENTS:
                out[c] = (dictionaries.COMPONENTS[c].smiles, "MDATK table")
        for c, smiles in parse_entries(s["custom"])[0]:
            if c in codes:
                out[c] = (smiles, "custom SMILES")
        if s["pubchem_fetch"]:
            for c, ident in parse_entries(s["pubchem_ids"], "CID")[0]:
                if c not in codes:
                    continue
                if preview:  # the wizard preview: fetched only when the files are written
                    notes.append(f"{c}: the SMILES of PubChem {ident} is fetched when the files are written")
                    continue
                try:
                    smiles = _PUBCHEM.get((ident, float(s["pubchem_timeout"])))
                    if smiles is None:
                        smiles = dictionaries.fetch_pubchem_smiles(ident, float(s["pubchem_timeout"]))
                        _PUBCHEM[(ident, float(s["pubchem_timeout"]))] = smiles
                    check = dictionaries.check_smiles(c, smiles) if c in dictionaries.COMPONENTS else []
                except dictionaries.DictionaryError as exc:
                    notes.append(f"WARNING: PubChem {ident} for {c} not used: {exc}")
                    continue
                for note in check or []:  # e.g. a neutral phosphate (PubChem lists acids)
                    notes.append(f"WARNING: PubChem {ident} for {c}: {note}; the dictionary keeps that "
                                 "protonation (use the MDATK table for the phosphodiester form)")
                out[c] = (smiles, f"PubChem {ident}")
        return out, notes

    def generate(self, s, ctx):
        codes, _ = self._codes(s, ctx)
        smiles, notes = self._smiles(s, codes, preview=getattr(ctx, "preview", False))
        program = s["program"]
        files: List[GeneratedFile] = []
        script = ctx.name(self.tag, "sh")
        sh = script_header(f"Restraint dictionaries ({PROGRAM_LABELS[program]}) for {' '.join(codes)}", ctx, s,
                           script, notes=notes)
        if program == "phenix.elbow":
            ver = PHENIX_VERSIONS[s["phenix_version"]]
            exe = ver["elbow"]
            if s["phenix_dir"].strip():
                sh += [f"# {ver['label']}",
                       f"source {shell_quote(os.path.join(s['phenix_dir'].strip(), ver['env_script']))}", ""]
        else:
            exe = "acedrg"
            if s["ccp4_setup"].strip():
                sh += ["# CCP4 (acedrg)", f"source {shell_quote(s['ccp4_setup'].strip())}", ""]
        sh += [f'command -v {exe} >/dev/null || {{ echo "ERROR: {exe} not found on PATH" >&2; exit 1; }}', ""]
        for note in notes:
            sh.append(f"echo {shell_quote(note)} >&2")
        if notes:
            sh.append("")
        helper = ctx.name("dictionaries", "py")
        source = inspect.getsource(dictionaries)
        files.append(GeneratedFile(helper, "#!/usr/bin/env python3\n"
                                   f"# Copied by {PROJECT_ABBREV} {__version__} (mdatk/dictionaries.py); standard "
                                   "library only.\n" + source, "helper",
                                   "renames the generated dictionaries to the CCD atom names (mdatk dict)"))
        extra = " ".join(extra_flags(s["program_args"]))
        for code in codes:
            smi_text, origin = smiles.get(code, ("", ""))
            comp = dictionaries.COMPONENTS.get(code)
            smi = ctx.name(code, "smi")
            files.append(GeneratedFile(smi, smi_text + "\n", "input", f"SMILES of {code} ({origin})"))
            work = f"work_{code}"
            out_cif = ctx.name(code, "cif")
            cmd = PROGRAM_COMMANDS[program].format(exe=exe, smi=f"../{smi}", code=code, out=code)
            if extra:
                cmd += " " + extra
            title = comp.name if comp else "custom residue"
            sh += [f"# {code}: {title} - SMILES from the {origin}"]
            if comp and comp.leaving:
                sh.append(f"# generated with the leaving atom {', '.join(comp.leaving)}; 'finish' removes it")
            log = f"{work}/{program}.log"
            sh += [f"rm -rf {work} && mkdir -p {work}",
                   f"( cd {work} && {cmd} ) > {log} 2>&1 \\",
                   f'    || {{ echo "ERROR: {program} failed for {code} (see {log})" >&2; exit 1; }}']
            finish = ["python3", helper, "finish", work, "--code", code, "--group", s["group"], "-o", out_cif]
            if comp is None:
                finish.append("--keep-names")
            sh += [" ".join(shell_quote(a) for a in finish), require_file(out_cif, "dictionaries.py finish"), ""]
        sh += [f'echo "Restraint dictionaries: {" ".join(ctx.name(c, "cif") for c in codes)}"', ""]
        files.append(GeneratedFile(script, "\n".join(sh), "run", f"runs {PROGRAM_LABELS[program]} and renames "
                                                                    "the atoms"))
        return files
