"""cpptraj wrapper: automated stripping, imaging and fitting.

The wrapper writes a cpptraj input script into a cache directory keyed by the
input files and cleaning parameters, runs cpptraj while streaming its log, and
records a completion marker.  A later request with unchanged inputs and
parameters reuses the cleaned files without running cpptraj again.
"""

from __future__ import annotations

import datetime as _dt
import logging
import os
import re
import shutil
import subprocess
import threading
from dataclasses import dataclass
from typing import Callable, Optional, Sequence

from .. import PROJECT_ABBREV, __version__
from ..config import CleaningParams, file_fingerprint, stable_hash
from ..io.cache import write_json
from ..progress import Cancelled

log = logging.getLogger(__name__)

CLEAN_PARM = f"{PROJECT_ABBREV}_cleaned.parm7"
CLEAN_TRAJ = f"{PROJECT_ABBREV}_cleaned.nc"
CLEAN_REF = f"{PROJECT_ABBREV}_cleaned_ref.pdb"
MARKER = f"{PROJECT_ABBREV}_clean.json"

_PERCENT = re.compile(r"(?<![\d.])(\d{1,3})%")


class CpptrajError(RuntimeError):
    pass


@dataclass
class CleanResult:
    topology: str
    trajectory: str
    reference_pdb: str
    script: str
    log: str
    out_dir: str
    key: str
    reused: bool


def find_cpptraj(path: str = "cpptraj") -> str:
    """Resolve the cpptraj executable (absolute path or a name on PATH)."""
    path = os.path.expanduser(path or "cpptraj")
    if os.sep in path:
        if os.path.isfile(path) and os.access(path, os.X_OK):
            return os.path.abspath(path)
        raise CpptrajError(f"cpptraj not executable at {path}")
    found = shutil.which(path)
    if not found:
        amberhome = os.environ.get("AMBERHOME")
        cand = os.path.join(amberhome, "bin", path) if amberhome else ""
        if cand and os.access(cand, os.X_OK):
            return cand
        raise CpptrajError(
            f"cpptraj ({path!r}) was not found on PATH. Install AmberTools or set the "
            "cpptraj path in the cleaning options.")
    return found


def cleaning_key(params: CleaningParams, topology: str, trajectories: Sequence[str]) -> str:
    relevant = {k: v for k, v in vars(params).items()
                if k not in ("enabled", "cpptraj_path", "output_dir")}
    return stable_hash({
        "version": 1,
        "topology": file_fingerprint(topology),
        "trajectories": [file_fingerprint(t) for t in trajectories],
        "reference": file_fingerprint(params.reference_file)
        if params.fit and params.fit_reference == "file" and params.reference_file else None,
        "params": relevant,
    })


def _quote(path: str) -> str:
    if '"' in path:
        raise CpptrajError(f"path contains a double quote: {path}")
    return f'"{path}"'


def _compact_mask(mask: str) -> str:
    # cpptraj splits command arguments on whitespace; masks never need it.
    return re.sub(r"\s+", "", mask or "")


def _strip_mask(params: CleaningParams) -> str:
    masks = [_compact_mask(m) for m in (params.solvent_mask, params.ion_mask,
                                        params.extra_strip_mask)]
    masks = [m for m in masks if m]
    return "|".join(f"({m})" for m in masks) if len(masks) > 1 else (masks[0] if masks else "")


def build_script(params: CleaningParams, topology: str, trajectories: Sequence[str],
                 out_dir: str) -> str:
    """Generate the cpptraj input script for the requested cleaning steps."""
    if not trajectories:
        raise CpptrajError("cleaning requires at least one trajectory")
    lines = [
        f"# Generated by {PROJECT_ABBREV} {__version__} on "
        f"{_dt.datetime.now().isoformat(timespec='seconds')}",
        f"parm {_quote(os.path.abspath(topology))}",
    ]
    stop = str(params.stop) if params.stop else "last"
    for t in trajectories:
        lines.append(f"trajin {_quote(os.path.abspath(t))} {max(1, params.start)} {stop} "
                     f"{max(1, params.offset)}")
    if params.fit and params.fit_reference == "frame":
        lines.append(f"reference {_quote(os.path.abspath(trajectories[0]))} "
                     f"{max(1, params.reference_frame)} [mdatkref]")
    elif params.fit and params.fit_reference == "file":
        if not params.reference_file:
            raise CpptrajError("fit reference 'file' selected but no reference file given")
        lines.append(f"reference {_quote(os.path.abspath(params.reference_file))} [mdatkref]")

    is_parm7 = os.path.splitext(topology)[1].lower() in (".parm7", ".prmtop", ".top")
    strip_mask = _strip_mask(params)
    if strip_mask:
        parmout = f" parmout {_quote(os.path.join(out_dir, CLEAN_PARM))}" if is_parm7 else ""
        lines.append(f"strip {strip_mask}{parmout}")
    elif is_parm7:
        lines.append(f"parmwrite out {_quote(os.path.join(out_dir, CLEAN_PARM))}")
    if params.autoimage:
        anchor = _compact_mask(params.autoimage_anchor)
        lines.append(f"autoimage anchor {anchor}" if anchor else "autoimage")
    if params.fit:
        if params.remove_box_after_fit:
            # Fitting rotates the unit cell, which NetCDF cannot store; the box is
            # meaningless after imaging + fitting anyway.
            lines.append("box nobox")
        mask = _compact_mask(params.fit_mask) or "!@H="
        ref = "first" if params.fit_reference == "first" else "ref [mdatkref]"
        lines.append(f"rms {PROJECT_ABBREV}fit {mask} {ref} mass")
    if params.extra_commands.strip():
        lines.extend(l.rstrip() for l in params.extra_commands.strip().splitlines())
    lines.append(f"trajout {_quote(os.path.join(out_dir, CLEAN_TRAJ))} netcdf")
    lines.append(f"trajout {_quote(os.path.join(out_dir, CLEAN_REF))} pdb onlyframes 1")
    lines.append("run")
    lines.append("quit")
    return "\n".join(lines) + "\n"


def run_cpptraj(executable: str, script_path: str, log_path: str, cwd: str,
                log_cb: Optional[Callable[[str], None]] = None,
                progress_cb: Optional[Callable[[float], None]] = None,
                cancel_event: Optional[threading.Event] = None) -> int:
    """Run cpptraj, streaming stdout/stderr line by line into ``log_cb``."""
    cmd = [executable, "-i", script_path]
    log.info("running %s", " ".join(cmd))
    with open(log_path, "w", encoding="utf-8") as logfh:
        proc = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                stdin=subprocess.DEVNULL, bufsize=0)
        buf = ""
        try:
            while True:
                if cancel_event is not None and cancel_event.is_set():
                    proc.terminate()
                    try:
                        proc.wait(timeout=10)
                    except subprocess.TimeoutExpired:
                        proc.kill()
                    raise Cancelled("cpptraj cancelled")
                chunk = proc.stdout.read1(4096) if hasattr(proc.stdout, "read1") else proc.stdout.read(4096)
                if not chunk:
                    break
                text = chunk.decode("utf-8", errors="replace")
                logfh.write(text)
                if progress_cb:
                    pct = _PERCENT.findall(text)
                    if pct:
                        progress_cb(min(100, int(pct[-1])) / 100.0)
                buf += text
                while "\n" in buf:
                    line, buf = buf.split("\n", 1)
                    if log_cb:
                        log_cb(line.rstrip())
            if buf and log_cb:
                log_cb(buf.rstrip())
        finally:
            if proc.poll() is None:
                proc.wait()
    return proc.returncode


def clean(params: CleaningParams, topology: str, trajectories: Sequence[str], cache_dir: str,
          log_cb: Optional[Callable[[str], None]] = None,
          progress_cb: Optional[Callable[[float], None]] = None,
          cancel_event: Optional[threading.Event] = None, force: bool = False) -> CleanResult:
    """Clean a trajectory with cpptraj, reusing a previous result when possible."""
    if not topology or not os.path.exists(topology):
        raise CpptrajError(f"topology not found: {topology}")
    for t in trajectories:
        if not os.path.exists(t):
            raise CpptrajError(f"trajectory not found: {t}")
    key = cleaning_key(params, topology, trajectories)
    out_dir = os.path.abspath(params.output_dir or os.path.join(cache_dir, "cleaned", key))
    is_parm7 = os.path.splitext(topology)[1].lower() in (".parm7", ".prmtop", ".top")
    top_out = os.path.join(out_dir, CLEAN_PARM if is_parm7 else CLEAN_REF)
    result = CleanResult(topology=top_out, trajectory=os.path.join(out_dir, CLEAN_TRAJ),
                         reference_pdb=os.path.join(out_dir, CLEAN_REF),
                         script=os.path.join(out_dir, "cpptraj.in"),
                         log=os.path.join(out_dir, "cpptraj.log"), out_dir=out_dir, key=key,
                         reused=False)
    marker = os.path.join(out_dir, MARKER)
    if not force and os.path.exists(marker) and all(
            os.path.exists(p) for p in (result.topology, result.trajectory)):
        import json
        try:
            with open(marker, "r", encoding="utf-8") as fh:
                info = json.load(fh)
        except (OSError, ValueError):
            info = {}
        if info.get("key") == key:
            result.reused = True
            msg = f"Reusing cleaned trajectory from {out_dir}"
            log.info(msg)
            if log_cb:
                log_cb(msg)
            return result

    exe = find_cpptraj(params.cpptraj_path)
    os.makedirs(out_dir, exist_ok=True)
    if os.path.exists(marker):
        os.remove(marker)
    script = build_script(params, topology, trajectories, out_dir)
    with open(result.script, "w", encoding="utf-8") as fh:
        fh.write(script)
    if log_cb:
        log_cb(f"cpptraj script written to {result.script}:")
        for line in script.splitlines():
            log_cb(f"    {line}")
    rc = run_cpptraj(exe, result.script, result.log, out_dir, log_cb, progress_cb, cancel_event)
    if rc != 0:
        raise CpptrajError(f"cpptraj failed with exit code {rc}; see {result.log}")
    missing = [p for p in (result.topology, result.trajectory) if not os.path.exists(p)]
    if missing:
        raise CpptrajError(f"cpptraj finished but did not write {missing}; see {result.log}")
    write_json(marker, {
        "project": PROJECT_ABBREV, "mdatk_version": __version__, "key": key,
        "created": _dt.datetime.now().isoformat(timespec="seconds"),
        "cpptraj": exe, "topology_in": os.path.abspath(topology),
        "trajectories_in": [os.path.abspath(t) for t in trajectories],
        "params": vars(params), "outputs": {
            "topology": result.topology, "trajectory": result.trajectory,
            "reference_pdb": result.reference_pdb},
    })
    if progress_cb:
        progress_cb(1.0)
    return result
